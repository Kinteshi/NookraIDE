package io.github.kinteshi.quirecode.assets

/**
 * A VS Code built-in language extension on Open VSX (namespace `vscode`): its TextMate grammar
 * and language configuration colour [extensions] and [filenames]. Versions and SHA-256 are
 * pinned here (from open-vsx.org, 2026-10-31), so a download is checked against what was
 * reviewed, not only against the server's own checksum.
 */
data class LanguagePack(
    val id: String,
    val displayName: String,
    val version: String,
    val sha256: String,
    val extensions: List<String>,
    val filenames: List<String>,
) {
    private val namespace: String get() = id.substringBefore('.')
    private val name: String get() = id.substringAfter('.')
    /** "SQL" from "SQL Language Basics (built-in)", for messages. */
    val languageName: String get() = displayName.substringBefore(" Language").substringBefore(" (built-in)").trim()
    val downloadUrl: String get() = "https://open-vsx.org/api/$namespace/$name/$version/file/$namespace.$name-$version.vsix"
}

/** The pack that colours [fileName]: by its exact name first (Dockerfile, Makefile), then its longest extension. */
fun languagePackFor(fileName: String): LanguagePack? {
    val lower = fileName.lowercase()
    LANGUAGE_PACKS.firstOrNull { pack -> pack.filenames.any { it.equals(fileName, ignoreCase = true) } }?.let { return it }
    val parts = lower.split('.')
    for (start in 1 until parts.size) {
        val extension = parts.drop(start).joinToString(".")
        LANGUAGE_PACKS.firstOrNull { extension in it.extensions }?.let { return it }
    }
    return null
}

